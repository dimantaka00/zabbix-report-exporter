from pathlib import Path
from datetime import datetime

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas


REPORT_DIR = Path("/app/storage/reports")
REPORT_DIR.mkdir(parents=True, exist_ok=True)


def generate_pdf(
    host_name: str,
    item_name: str,
    units: str,
    source: str,
    time_from: int,
    time_till: int,
    points: list[dict],
) -> Path:

    filename = (
        f"report_"
        f"{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    )

    output = REPORT_DIR / filename

    pdf = canvas.Canvas(
        str(output),
        pagesize=A4,
    )

    width, height = A4

    pdf.setTitle("Zabbix Monitoring Report")

    # Title
    pdf.setFont("Helvetica-Bold", 18)
    pdf.drawString(
        50,
        height - 50,
        "ZABBIX MONITORING REPORT",
    )

    pdf.setFont("Helvetica", 10)

    y = height - 80

    pdf.drawString(
        50,
        y,
        f"Host: {host_name}",
    )

    y -= 18

    pdf.drawString(
        50,
        y,
        f"Item: {item_name}",
    )

    y -= 18

    pdf.drawString(
        50,
        y,
        f"Unit: {units or '-'}",
    )

    y -= 18

    pdf.drawString(
        50,
        y,
        f"Source: {source}",
    )

    y -= 18

    start = datetime.fromtimestamp(time_from)
    end = datetime.fromtimestamp(time_till)

    pdf.drawString(
        50,
        y,
        f"Period: {start} - {end}",
    )

    y -= 35

    # Chart area
    chart_x = 60
    chart_y = 180
    chart_width = 470
    chart_height = 280

    pdf.rect(
        chart_x,
        chart_y,
        chart_width,
        chart_height,
    )

    if points:

        values = [float(p["value"]) for p in points]

        min_value = min(values)
        max_value = max(values)

        if min_value == max_value:
            min_value -= 1
            max_value += 1

        plot_left = chart_x + 35
        plot_bottom = chart_y + 30
        plot_width = chart_width - 50
        plot_height = chart_height - 50

        # Y labels
        pdf.setFont("Helvetica", 8)

        pdf.drawString(
            chart_x + 5,
            plot_bottom,
            f"{min_value:.2f}",
        )

        pdf.drawString(
            chart_x + 5,
            plot_bottom + plot_height,
            f"{max_value:.2f}",
        )

        # Line chart
        pdf.setLineWidth(1)

        previous = None

        count = max(len(points) - 1, 1)

        for index, point in enumerate(points):

            x = (
                plot_left
                + (index / count) * plot_width
            )

            normalized = (
                (point["value"] - min_value)
                / (max_value - min_value)
            )

            chart_point_y = (
                plot_bottom
                + normalized * plot_height
            )

            if previous:
                pdf.line(
                    previous[0],
                    previous[1],
                    x,
                    chart_point_y,
                )

            previous = (
                x,
                chart_point_y,
            )

    else:

        pdf.setFont("Helvetica", 12)

        pdf.drawCentredString(
            width / 2,
            chart_y + chart_height / 2,
            "No data available",
        )

    pdf.setFont("Helvetica", 8)

    pdf.drawString(
        50,
        50,
        "Generated by Zabbix Report Exporter",
    )

    pdf.save()

    return output